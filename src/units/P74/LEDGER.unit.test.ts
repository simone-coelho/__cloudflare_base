/** The code block of section 3 of the integration guide, verbatim (P34 T5's). */
function tenLines(): string {
  const guide = readTree('docs/kit/01-integration-guide.md');
  const section = guide.split(/\n## /).find(x => /^3\. /.test(x));
  const code = section?.match(/```js\n([\s\S]*?)```/)?.[1];
  expect(code, 'PRECONDITION: section 3 of the integration guide carries its code block').toBeTruthy();
  return code!;
}
/** Runs the code block as written over `s`; returns what the page painted, with the decision each paint was handed (P34 T5's). */
function example(s: Sdk): Array<{ id: string; decisionId?: string }> {
  const painted: Array<{ id: string; decisionId?: string }> = [];
  let current: ContentDecision | undefined;
  const client = { listen: s.listen, emit: s.emit, connect: () => s.core.connect() };
  const renderHero = (customerContentId: string) => { painted.push({ id: customerContentId, decisionId: current?.decisionId }); return true; };
  const renderDefaultHero = () => { painted.push({ id: 'default' }); };
  const listen = { ...s.listen, subscribe: (slot: string, cb: (ds: ContentDecision[], set: DecisionSet) => void) => s.listen.subscribe(slot, (ds, set) => { current = ds[0]; cb(ds, set); }) };
  const run = new Function('client', 'renderHero', 'renderDefaultHero', 'heroElement', tenLines()) as (...args: unknown[]) => void;
  run({ ...client, listen }, renderHero, renderDefaultHero, EL);
  return painted;
}
const HERO = { page: 'home', arm: 'personalized', decisions: [decision('hero', 0, 'hero.tabby.first', 'on-model')] };

describe('unit:P74.CR2', () => {
  it('sdk: after a close, the reconnect (the welcome frame after its open) makes exactly one snapshot request, for the page view that was open, and its answer is painted; the reconnect is reported once (reconnecting, connecting, connected)', async () => {
    const s = sdk();
    await s.core.ready();
    const painted = paintsOf(s);
    void s.listen.refresh({ page: 'pdp' });
    await settle();
    await answerPending(s, FIRST, 'first');
    s.core.connect();
    await settle();
    await openAsHosted(s);
    await answerPending(s, FIRST, 'after-open');
    expect([s.snapshots.length, s.core.socketStatus], 'PRECONDITION: one snapshot request, the socket connected').toEqual([1, 'connected']);
    s.statuses.length = 0;
    s.f.sockets.at(-1)!.close();
    await settle();
    await vi.advanceTimersByTimeAsync(s.core.config.reconnectMs);
    expect(s.f.sockets.length, 'PRECONDITION: after the close the SDK opened a second socket').toBe(2);
    await openAsHosted(s);
    await answerPending(s, LATER, 'reconnect');
    expect.soft(s.snapshots.map(x => x.pageInstance), 'P74.CR2 — the reconnect asks once, for the page view that was open, counted once despite the welcome frame (today it asks nothing)').toEqual([s.snapshots[0]!.pageInstance, s.snapshots[0]!.pageInstance]);
    expect.soft(painted, 'P74.CR2 — the reconnect\'s answer is painted').toEqual([[GRID, RECO, LOOK], [LOOK, GRID, EDIT]]);
    expect.soft(s.statuses, 'P74.CR2 — the reconnect is reported once: reconnecting, connecting, connected (today connected twice)').toEqual(['reconnecting', 'connecting', 'connected']);
    expect(s.core.socketStatus, 'P74.CR2 — socketStatus reads connected').toBe('connected');
    s.destroy();
  });

  it('sdk: LOCK — the kit\'s ten-line example (P34 T5) with the welcome frame after the open: on a browser that holds a session (the open during the first snapshot) and on a fresh browser (the open after the first answer), the first answer is painted and acknowledged and the page view makes one snapshot request', async () => {
    const held = sdk();
    await held.core.ready();
    const heldPainted = example(held);
    await settle();
    await openAsHosted(held);
    expect(held.snapshots.length, 'PRECONDITION: the example asked for the page once').toBe(1);
    held.snapshots[0]!.answer(HERO, 'first');
    await settle();
    await answerPending(held, { ...HERO, decisions: [decision('hero', 0, 'hero.tabby.second', 'on-model')] }, 'refresh');
    const fresh = sdk();
    const freshPainted = example(fresh);
    await settle();
    expect(fresh.snapshots.length, 'PRECONDITION: on a fresh browser, the example asked for the page once').toBe(1);
    fresh.snapshots[0]!.answer(HERO, 'first');
    await settle();
    expect(fresh.f.sockets.length, 'PRECONDITION: on a fresh browser, the example\'s socket exists once the first answer has issued the session').toBe(1);
    await openAsHosted(fresh);
    await answerPending(fresh, { ...HERO, decisions: [decision('hero', 0, 'hero.tabby.second', 'on-model')] }, 'refresh');
    const acks = (s: Sdk) => s.actions.filter(a => a.type === 'content_impression').map(a => [a.data.decisionId, a.status]);
    expect.soft({ held: [heldPainted[0], acks(held), held.snapshots.length], fresh: [freshPainted[0], acks(fresh), fresh.snapshots.length] },
      'P74.CR2 — LOCK: with the welcome frame, the example paints the first answer, acknowledges it and asks once (P34 T5\'s count clauses)').toEqual({
      held: [{ id: 'TAP-HERO-TABBY-FIRST', decisionId: 'first-hero-0-hero.tabby.first' }, [['first-hero-0-hero.tabby.first', 200]], 1],
      fresh: [{ id: 'TAP-HERO-TABBY-FIRST', decisionId: 'first-hero-0-hero.tabby.first' }, [['first-hero-0-hero.tabby.first', 200]], 1] });
    held.destroy(); fresh.destroy();
  });
});
