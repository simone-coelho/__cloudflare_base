describe('unit:P74.CR1', () => {
  it('sdk: a socket opening after the page view\'s first answer, the server\'s welcome frame after its open: the page view makes one snapshot request, the open is reported once (connecting, connected) and socketStatus reads connected', async () => {
    const s = sdk();
    await s.core.ready();
    const painted = paintsOf(s);
    void s.listen.refresh({ page: 'pdp' });
    await settle();
    expect(s.snapshots.length, 'PRECONDITION: the page view asked for its first answer').toBe(1);
    await answerPending(s, FIRST, 'first');
    s.statuses.length = 0;
    s.core.connect();
    await settle();
    await openAsHosted(s);
    // Whatever the open asks is answered, so a request coalesced behind it is asked too.
    await answerPending(s, LATER, 'after-open');
    expect.soft(s.statuses, 'P74.CR1 — the open is reported once: connecting, then connected, the welcome frame adding nothing (today connected twice, core.ts:1176)').toEqual(['connecting', 'connected']);
    expect.soft(s.snapshots.length, 'P74.CR1 — the page view makes one snapshot request: the open asks nothing (P81\'s form)').toBe(1);
    expect.soft(painted, 'P74.CR1 — the page shows its first answer and nothing else').toEqual([[GRID, RECO, LOOK]]);
    expect(s.core.socketStatus, 'P74.CR1 — socketStatus reads connected').toBe('connected');
    s.destroy();
  });

  it('sdk: a socket opening while the page view\'s first snapshot is in flight, the welcome frame after its open: the first answer is painted and no request follows it (P81\'s R10 of P34 T5), the open reported once', async () => {
    const s = sdk();
    await s.core.ready();
    const painted = paintsOf(s);
    void s.listen.refresh({ page: 'pdp' });
    await settle();
    expect(s.snapshots.length, 'PRECONDITION: the first snapshot is in flight').toBe(1);
    s.statuses.length = 0;
    s.core.connect();
    await settle();
    await openAsHosted(s);
    s.snapshots[0]!.answer(FIRST, 'first');
    await settle();
    await answerPending(s, LATER, 'after-open');
    expect.soft(s.statuses, 'P74.CR1 — the open is reported once: connecting, then connected (today connected twice)').toEqual(['connecting', 'connected']);
    expect.soft([s.snapshots.length, painted], 'P74.CR1 — the in-flight first answer is painted and nothing follows it: one snapshot request').toEqual([1, [[GRID, RECO, LOOK]]]);
    expect(s.core.socketStatus, 'P74.CR1 — socketStatus reads connected').toBe('connected');
    s.destroy();
  });
});

